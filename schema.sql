create table organizacao (
  id bigint generated by default as identity primary key,
  missao text, visao text, valores text
);
insert into organizacao (missao, visao, valores) values ('', '', '');

create table temas (
  id bigint generated by default as identity primary key,
  nome text not null,
  cor text default '#2563eb',
  descricao text
);

create table objetivos (
  id bigint generated by default as identity primary key,
  perspectiva text not null check (perspectiva in ('financeira','clientes','processos','aprendizado')),
  titulo text not null,
  responsavel text,
  tema_id bigint references temas(id) on delete set null
);

create table kpis (
  id bigint generated by default as identity primary key,
  objetivo_id bigint not null references objetivos(id) on delete cascade,
  nome text not null,
  unidade text,
  meta numeric,
  atual numeric default 0,
  menor_melhor boolean default false  -- true: quanto menor, melhor (ex.: custos)
);

create table iniciativas (
  id bigint generated by default as identity primary key,
  objetivo_id bigint not null references objetivos(id) on delete cascade,
  titulo text not null,
  prazo date,
  status text default 'Não iniciada' check (status in ('Não iniciada','Em andamento','Concluída'))
);

-- Causa e efeito: "origem" contribui para "destino"
create table relacoes (
  id bigint generated by default as identity primary key,
  origem_id bigint not null references objetivos(id) on delete cascade,
  destino_id bigint not null references objetivos(id) on delete cascade,
  unique (origem_id, destino_id)
);

-- Segurança (RLS): libera leitura/escrita para quem tem a chave "anon".
-- ATENÇÃO: quem tiver o link do app poderá editar os dados.
do $$
declare t text;
begin
  foreach t in array array['organizacao','temas','objetivos','kpis','iniciativas','relacoes'] loop
    execute format('alter table %I enable row level security', t);
    execute format('create policy "acesso_app" on %I for all to anon using (true) with check (true)', t);
  end loop;
end $$;
